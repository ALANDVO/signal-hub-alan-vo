"""LLM advisory analysis service for PHP issues."""

import json
import os
from typing import Optional
from dataclasses import dataclass
from abc import ABC, abstractmethod

import httpx
from app.core.config import get_settings

settings = get_settings()


@dataclass
class LLMAnalysisResult:
    """Result of LLM analysis."""
    advisory_text: str
    disclaimer: str
    model_used: str
    provider: str


class LLMProvider(ABC):
    """Abstract base class for LLM providers."""

    @abstractmethod
    async def analyze(self, prompt: str) -> LLMAnalysisResult:
        """Analyze issue with LLM and return result with disclaimer."""
        pass

    @abstractmethod
    def is_configured(self) -> bool:
        """Check if provider is properly configured."""
        pass


class OpenAICompatibleProvider(LLMProvider):
    """OpenAI-compatible API provider (OpenAI, Ollama, LM Studio, etc.)."""

    def __init__(self):
        self.api_key = settings.LLM_API_KEY
        self.base_url = settings.LLM_BASE_URL or "https://api.openai.com/v1"
        self.model = settings.LLM_MODEL
        self.timeout = 30.0

    def is_configured(self) -> bool:
        return bool(self.api_key and self.model)

    async def analyze(self, prompt: str) -> LLMAnalysisResult:
        if not self.is_configured():
            raise RuntimeError("LLM provider not configured: missing API key or model")

        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }

        payload = {
            "model": self.model,
            "messages": [
                {
                    "role": "system",
                    "content": (
                        "You are a PHP internals expert. Analyze the issue and provide "
                        "technical advisory guidance. Be concise and accurate. "
                        "Do not make up information; if uncertain, say so."
                    ),
                },
                {"role": "user", "content": prompt},
            ],
            "temperature": 0.2,
            "max_tokens": 1000,
        }

        async with httpx.AsyncClient(timeout=self.timeout) as client:
            response = await client.post(
                f"{self.base_url.rstrip('/')}/chat/completions",
                headers=headers,
                json=payload,
            )
            response.raise_for_status()
            data = response.json()

        content = data["choices"][0]["message"]["content"]

        disclaimer = (
            "⚠️ ADVISORY ONLY: This analysis is generated by an AI model and may contain "
            "inaccuracies. It is not a substitute for official PHP project guidance or "
            "expert review. Verify all technical claims independently."
        )

        return LLMAnalysisResult(
            advisory_text=content,
            disclaimer=disclaimer,
            model_used=self.model,
            provider="openai-compatible",
        )


class MockProvider(LLMProvider):
    """Mock provider for testing without API credentials."""

    def __init__(self):
        self._configured = True

    def is_configured(self) -> bool:
        return self._configured

    async def analyze(self, prompt: str) -> LLMAnalysisResult:
        return LLMAnalysisResult(
            advisory_text=(
                "MOCK ANALYSIS: This is a simulated LLM response for testing. "
                "The actual issue would be analyzed by the configured LLM provider. "
                f"Prompt length: {len(prompt)} characters."
            ),
            disclaimer=(
                "⚠️ ADVISORY ONLY: This analysis is generated by an AI model and may contain "
                "inaccuracies. It is not a substitute for official PHP project guidance or "
                "expert review. Verify all technical claims independently."
            ),
            model_used="mock-model",
            provider="mock",
        )


def get_llm_provider() -> LLMProvider:
    """Get the configured LLM provider instance."""
    provider_type = settings.LLM_PROVIDER.lower()

    if provider_type == "mock":
        return MockProvider()
    elif provider_type == "openai-compatible":
        return OpenAICompatibleProvider()
    else:
        # Default to mock for safety
        return MockProvider()


def build_analysis_prompt(
    title: str,
    body: str,
    issue_type: str,
    confidence: float,
    php_version: Optional[str] = None,
    os: Optional[str] = None,
) -> str:
    """Build the prompt for LLM analysis."""
    parts = [
        f"PHP Issue Analysis Request",
        f"============================",
        f"",
        f"Title: {title}",
        f"",
        f"Body: {body}",
        f"",
        f"Pre-classified Type: {issue_type} (confidence: {confidence:.1%})",
    ]

    if php_version:
        parts.append(f"PHP Version: {php_version}")
    if os:
        parts.append(f"OS: {os}")

    parts.extend([
        f"",
        f"Please provide:",
        f"1. Root cause analysis based on PHP internals knowledge",
        f"2. Potential fix approaches or workarounds",
        f"3. Related PHP internals components (extensions, SAPIs, etc.)",
        f"4. Any known similar issues or RFCs",
        f"5. Testing considerations",
    ])

    return "\n".join(parts)


async def analyze_with_llm(
    title: str,
    body: str,
    issue_type: str,
    confidence: float,
    php_version: Optional[str] = None,
    os: Optional[str] = None,
) -> LLMAnalysisResult:
    """
    Analyze a PHP issue with LLM advisory.

    Args:
        title: Issue title
        body: Issue body/description
        issue_type: Pre-classified issue type
        confidence: Classification confidence
        php_version: Optional PHP version
        os: Optional OS

    Returns:
        LLMAnalysisResult with advisory text and disclaimer

    Raises:
        RuntimeError: If LLM provider is not configured or request fails
    """
    provider = get_llm_provider()

    if not provider.is_configured():
        raise RuntimeError(
            "LLM advisory analysis not available. "
            "Configure LLM_API_KEY, LLM_MODEL, and optionally LLM_BASE_URL."
        )

    prompt = build_analysis_prompt(
        title=title,
        body=body,
        issue_type=issue_type,
        confidence=confidence,
        php_version=php_version,
        os=os,
    )

    return await provider.analyze(prompt)

